#!/usr/bin/env python3
"""Package the recorded explorer for GitHub Pages and anonymous mirrors.

No experiments, requests to models, or external data fetches are performed.
The ESM source remains available for offline tests; the browser bundle and
data companions are ordinary scripts compatible with opaque-origin sandboxes.
"""
from pathlib import Path
import base64
import hashlib
import json
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'site'


def main():
    core = re.sub(r'^export ', '', (SITE / 'core.js').read_text(), flags=re.M)
    app = re.sub(r'^import .*?;\n', '', (SITE / 'app.js').read_text(), flags=re.M)
    lab = re.sub(r'^import .*?;\n|^export ', '', (SITE / 'lab.js').read_text(), flags=re.M)
    world = re.sub(r'^export ', '', (SITE / 'world.js').read_text(), flags=re.M)
    bundle = "// Generated by scripts/build_anonymous_site.py.\n(async () => {\n'use strict';\n"
    bundle += core + '\n' + world + '\n' + lab + '\nconst E = esc;\n' + app + '\n})();\n'
    (SITE / 'browser.js').write_text(bundle)
    files = sorted((SITE / 'data').rglob('*.json')) + sorted((SITE / 'data').rglob('*.json.gz'))
    verified = []
    for path in files:
        raw = path.read_bytes()
        key = path.relative_to(SITE).as_posix()
        encoded = base64.b64encode(raw).decode('ascii')
        payload = f'globalThis.LUMEN_DATA.register({json.dumps(key)},{json.dumps(encoded)});\n'
        target = path.with_name(path.name + '.js')
        target.write_text(payload, encoding='ascii')
        assert base64.b64decode(encoded) == raw
        assert target.stat().st_size < 8_000_000, target
        verified.append({'path': key, 'sha256': hashlib.sha256(raw).hexdigest()})
    shutil.copyfile(ROOT / 'release/lumen-bench.pdf', SITE / 'assets/lumen-bench.pdf')
    # Pages uses main:/docs, so the repository and website share one mirror.
    for path in SITE.rglob('*'):
        if path.is_file():
            dest = ROOT / 'docs' / path.relative_to(SITE)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, dest)
    (ROOT / 'docs/.nojekyll').write_text('')
    (ROOT / 'analysis/verification/anonymous_browser_payloads.json').write_text(
        json.dumps({'payloads': verified, 'original_bytes_preserved': True}, indent=2) + '\n')
    print(json.dumps({'payload_files': len(files), 'pages_source': 'main:/docs', 'data_changed': False}))


if __name__ == '__main__':
    main()
